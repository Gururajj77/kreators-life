1. Set **Hours of planned work a day**. It starts at four.
2. Higher priority tasks are placed first, each on the lightest day it fits.
3. **Plan strength** says Strong, Fair or Light. Days with something planned, days that are not overloaded, and tasks with a length all help.
4. **Worth a look** lists anything to fix, like a heavy day, a block that is too full, or a task with no length. Each line has a **Fix**.
5. Each suggestion shows its block under the title, picked from the task''s area of life and pillar. A select beside it changes the block.
6. **Add your own** finds any open task by name and plans it here too.
