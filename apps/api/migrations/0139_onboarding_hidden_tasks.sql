- Tap a day to see its tasks, tick them, or **Add a task on this day**.
- Each day wears a small mark in its kind of day''s colour. In the day''s sheet, **Kind of day** sets the kind for that date, past or future. **Follow your week** puts it back.
- **Print this month** gives you a clean paper copy.

## Plan my week

