6. **Time** and **Minutes:** when you will do it, and how long it should take. Quick picks run from 15 minutes to an hour and a half.
7. **Subtasks:** small steps inside the task, up to twenty. They pay nothing and never stop you ticking the task.

Tap **Save plan**. Once a task has minutes, **Start focus** opens Mindfulness with the task picked and the timer set to that length. **Delete task**, at the foot of the plan, asks first.

> **Pro tip:** the do date and the due date are not the same thing. The do date is when you will work on it. The due date is when it must be done. The do date can never come after the due date.

## Sorting the list

- **Kind of day:** a dropdown that starts on **Follow your week**, with the day template your week gives today, like Everyday. Pick another, like Deep work day, Family day or Low energy day, to change today only. Your kind of day is a day template. Part three of Daily covers them.
- **Area:** shows once a task has an area. Pick one area, every area, or No area.
- **Sort:** Day, Priority, Due date, By context, By time block or By area, at the right beside **Area**. By context keeps P0 on top. Inside each priority, it puts first the pillar your day template leads with. **Past due** keeps its own sort.
- **By time block** and **By area** show your tasks in coloured boxes you can open and fold, with P0 first in each box.
- **View:** the eye at the end of the row. It hides parts of Daily you do not use, like **Habits** or **Month calendar**, on every device. A quiet line says how many are hidden, with **Show all**.

## Place my day

Under **Your day**, a line says how many of today''s tasks with no block or time fit your blocks. **Place my day** gives each one a start in the block that fits, P0 first, never on top of a task that already has a time. Nothing is saved until you tap it. A task that repeats waits for a time from you, since its time would carry to the next ones.

## Adding a task

Under the list, open **Add a task**. Type the task, pick which project it holds up, and add it. A line under it says where it went. A task always hangs from a project, so it always has a reason.

## The lists below

- **Not scheduled yet:** tasks with no do date and no due date. They stay out of Tasks until you pick a day. Then they move up.
- **Done today:** what you ticked, struck through, with the time. It starts folded, with the day''s count beside it; tap it to open. Tap one to untick it. That takes back its xp. It shows ten at a time. Pick 25 or 50 under it, or go to the next page.
- **Hidden tasks:** tasks you hid from your lists. In a task''s plan, tap **Hide this task**, then **Until tomorrow** or **Until I unhide it**. A hidden task sends no reminder and keeps its days. It waits in this fold, last under Tasks, with **Unhide** under it. A tick there still counts.

## Close the unfinished

