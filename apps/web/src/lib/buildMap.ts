/** How much of a list of items is done: built counts in full, a key or test mode counts half, not built counts nothing. */
const WEIGHT: Record<BuildState, number> = { ok: 1, key: 0.5, test: 0.5, off: 0 };
export const percentOf = (items: readonly BuildItem[]): number => Math.round((items.reduce((n, i) => n + WEIGHT[i[1]], 0) / Math.max(1, items.length)) * 100);
export const itemsOf = (card: BuildCard): readonly BuildItem[] => [...card.items, ...(card.extra ?? [])];
