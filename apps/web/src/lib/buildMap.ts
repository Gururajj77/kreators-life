/**
 * The build map: what is built, what waits on a key, what runs in test mode and what is not built, by section and card.
 * It is shown on Observability (Build map), as data and not as a page in another tab. Edit a state here and the rings, bars and
 * the tower on that page follow. States: ok (built and checked), key (needs a key), test (test mode or not checked live), off (not built).
 */
export type BuildState = 'ok' | 'key' | 'test' | 'off';
export type BuildItem = readonly [label: string, state: BuildState, note?: string];
export type BuildVisual = 'blocks' | 'pipe' | 'ladder' | 'boxes' | 'tiles' | 'keys';
export interface BuildCard {
  title: string;
  route?: string;
  visual: BuildVisual;
  wide?: boolean;
  items: readonly BuildItem[];
  /** More blocks under the main ones, counted in the ring. */
  extra?: readonly BuildItem[];
}
export interface BuildSection {
  id: string;
  name: string;
  short: string;
  /** 1 to 7: which relationship colour the floor wears. */
  floor: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  blurb: string;
  cards: readonly BuildCard[];
}

