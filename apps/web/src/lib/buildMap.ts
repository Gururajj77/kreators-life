/**
 * The build map: what is built, what waits on a key, what runs in test mode and what is not built, by section and card.
 * It is shown on Dev Tools (Build map), as data and not as a page in another tab. Edit a state here and the rings, bars and
 * the tower on that page follow. States: ok (built and checked), key (needs a key), test (test mode, or not tried live, or checked
 * only by hand), off (not built).
 *
 * Honest by rule (2026-11-09): an item is `ok` only when a smoke check or a drive is behind it, and its card names that check in
 * `checks`. `scripts/check-buildmap.mjs` (run by scripts/scan.sh) fails when a named file, script or smoke section is missing, when a
 * route a card or an item names is not a route in App.tsx, and when a card with a built item names no check.
 */
export type BuildState = 'ok' | 'key' | 'test' | 'off';
export type BuildItem = readonly [label: string, state: BuildState, note?: string];
export type BuildVisual = 'blocks' | 'pipe' | 'ladder' | 'boxes' | 'tiles' | 'keys';
export interface BuildCard {
  title: string;
  /** Where it lives in the app: routes (each one that starts with a slash is a route in App.tsx), or plain words. */
  route?: string;
  visual: BuildVisual;
  wide?: boolean;
  items: readonly BuildItem[];
  /** More blocks under the main ones, counted in the ring. */
  extra?: readonly BuildItem[];
  /** The files to open for this card, from the repo root. Each must exist. */
  files?: readonly string[];
  /** What checks it: a section of the smoke test (`smoke: Fitness`) or a script under scripts/. Each must exist. */
  checks?: readonly string[];
}
export interface BuildSection {
  id: string;
  name: string;
  short: string;
  /** 1 to 7: which relationship colour the floor wears. */
  floor: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  blurb: string;
  cards: readonly BuildCard[];
}

